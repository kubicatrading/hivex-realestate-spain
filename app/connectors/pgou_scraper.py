"""
PGOU Urban Planning Connector & National Gazette Monitor Module
Parses urban planning opportunities, re-zonings, Partial Plans (Planes Parciales),
and PGOU modifications across Spain's metropolitan and provincial areas.
Batch-processed to avoid server timeouts and scale seamlessly nationwide.
"""

from typing import List, Dict, Any, Optional

class PGOUScraper:
    """
    Connector for urban planning development opportunities, partial plans (Planes Parciales),
    PAIs, and land management sectors across Spain.
    """

    def __init__(self):
        self._all_opportunities: List[Dict[str, Any]] = self._build_national_catalog()

    def fetch_pgou_opportunities(
        self,
        limit: Optional[int] = None,
        offset: int = 0,
        province: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        """
        Retrieves active urban planning development opportunities detected across
        municipal planning departments and urban management boards in Spain.
        Supports batching and filtering to prevent timeouts.
        """
        items = self._all_opportunities

        if province:
            p_clean = province.strip().lower()
            items = [item for item in items if p_clean in item.get("province", "").lower()]

        if offset > 0:
            items = items[offset:]

        if limit is not None and limit > 0:
            items = items[:limit]

        return items

